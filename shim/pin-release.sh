#!/usr/bin/env bash
# Pin the prebuilt shim archives in build.zig.zon for -Dshim=prebuilt.
#
#   shim/pin-release.sh shim-v0.1.0         # the GitHub release for that tag
#   shim/pin-release.sh --base-url http://127.0.0.1:8765   # any server with iroh-shim-*.tar.gz (CI self-check)
#
# Each archive becomes a lazy dependency named iroh_shim_<target>, so a build
# downloads only its own target. Zig hashes the unpacked contents, so the pin
# holds whatever server serves the bytes.
set -euo pipefail

TARGETS=(${SHIM_TARGETS:-linux-x86_64 linux-aarch64 macos-universal windows-x86_64 windows-aarch64})
REPO_URL="${REPO_URL:-https://github.com/progrium/moonsec}"
root="$(cd "$(dirname "$0")/.." && pwd)"
zon="$root/build.zig.zon"

if [ "${1:-}" = "--base-url" ]; then
  base="${2:?--base-url needs a URL}"
  url_for() { echo "$base/iroh-shim-$1.tar.gz"; }
  label="archives from $base"
else
  tag="${1:?usage: pin-release.sh <shim-vX.Y.Z> | --base-url <url>}"
  url_for() { echo "$REPO_URL/releases/download/$tag/iroh-shim-$1.tar.gz"; }
  label="$tag"
fi

if ! grep -q '// shim-release-begin' "$zon" || ! grep -q '// shim-release-end' "$zon"; then
  echo "build.zig.zon lacks the shim-release-begin/end markers inside .dependencies" >&2
  exit 1
fi

block="$(mktemp)"
trap 'rm -f "$block"' EXIT
{
  echo "        // shim-release-begin: generated by shim/pin-release.sh, used by -Dshim=prebuilt"
  echo "        // $label"
  for t in "${TARGETS[@]}"; do
    url="$(url_for "$t")"
    # zig fetch must run inside a Zig project; it prints the package hash.
    hash="$(cd "$root" && zig fetch "$url")"
    echo "        .iroh_shim_${t//-/_} = .{"
    echo "            .url = \"$url\","
    echo "            .hash = \"$hash\","
    echo "            .lazy = true,"
    echo "        },"
  done
  echo "        // shim-release-end"
} > "$block"

# Replace everything between the markers (inclusive) with the new block.
awk -v blockfile="$block" '
  /\/\/ shim-release-begin/ { while ((getline l < blockfile) > 0) print l; skip = 1; next }
  /\/\/ shim-release-end/   { skip = 0; next }
  !skip { print }
' "$zon" > "$zon.tmp" && mv "$zon.tmp" "$zon"
echo "pinned $label in build.zig.zon" >&2
